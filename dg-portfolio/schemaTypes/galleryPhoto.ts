import { defineField, defineType } from 'sanity'

export default defineType({
  name: 'galleryPhoto',
  title: 'Home Gallery Photo',
  type: 'document',
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
    }),
    defineField({
      name: 'image',
      title: 'Image',
      type: 'image',
      options: {
        hotspot: true,
      }
    }),
    defineField({
      name: 'order',
      title: 'Display Order',
      type: 'number',
    })
  ],
  orderings: [
    {
      title: 'Display Order',
      name: 'orderAsc',
      by: [{field: 'order', direction: 'asc'}],
    }
  ]
})
